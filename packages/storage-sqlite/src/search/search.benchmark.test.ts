const NODE_COUNT = 10_000;
const RELATIONSHIP_COUNT = 30_000;
const TAG_COUNT = 200;
const GENERATED_WORD_COUNT = 3_000;
const SETUP_TIMEOUT_MS = 600_000;

const WORKSPACE_ID = '90000000-0000-4000-8000-000000000001' as WorkspaceId;
const TIMESTAMP = '2026-10-26T12:00:00.000Z' as UtcTimestamp;

/** Deterministic canonical UUID; `kind` keeps node, relationship and tag IDs disjoint. */
function uuid(kind: number, counter: number): string {
  return `${kind.toString(16).padStart(8, '0')}-0000-4000-8000-${counter.toString(16).padStart(12, '0')}`;
}

/** Mulberry32: tiny seeded PRNG with good enough distribution for test data. */
function createRandom(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4_294_967_296;
  };
}

const COMMON_WORDS = (
  'the of and to in is that for as with on by are this be from at an which it or energy ' +
  'system theory model function law field state process structure learning memory network ' +
  'value change force light wave particle cell gene language history economy market time ' +
  'space matter data proof number set group graph order logic signal power heat entropy'
).split(' ');

const HEBREW_WORDS = (
  'שלום עולם ידע למידה זיכרון רשת מושג קשר תורה מדע פיזיקה כימיה ביולוגיה היסטוריה שפה ' +
  'מתמטיקה הוכחה משפט תא אנרגיה כוח אור גל חלקיק מבנה תהליך מערכת ערך שינוי זמן מרחב'
).split(' ');

const SYLLABLES = (
  'ka lo mi ne ru sa te vo zi pa do fe gu ha ji ko lu ma no pi qua re si tu ve wa xe yo za ' +
  'bri cla dro fen gor hal jun kel mor nip ost pra que ris sto tri und vex wil zor'
).split(' ');

/** Builds the vocabulary: common words first (most frequent), then generated and Hebrew words. */
function buildVocabulary(random: () => number): string[] {
  const words = new Set(COMMON_WORDS);
  while (words.size < COMMON_WORDS.length + GENERATED_WORD_COUNT) {
    const syllableCount = 2 + Math.floor(random() * 3);
    let word = '';
    for (let index = 0; index < syllableCount; index += 1) {
      word += SYLLABLES[Math.floor(random() * SYLLABLES.length)] ?? '';
    }
    words.add(word);
  }
  const vocabulary = [...words];
  // Spread Hebrew words through the frequency range instead of clustering them at the tail.
  HEBREW_WORDS.forEach((word, index) => {
    vocabulary.splice(60 + index * 90, 0, word);
  });
  return vocabulary;
}

interface Dataset {
  readonly vocabulary: readonly string[];
  readonly titles: readonly string[];
  readonly nodeIds: readonly NodeId[];
  readonly tagIds: readonly TagId[];
}

interface Generator {
  readonly random: () => number;
  /** Skewed pick: low indexes (common words) are far more likely than the tail. */
  word(): string;
  words(min: number, max: number): string;
  integer(min: number, max: number): number;
  pick<Item>(items: readonly Item[]): Item;
}

function createGenerator(seed: number, vocabulary: readonly string[]): Generator {
  const random = createRandom(seed);
  const integer = (min: number, max: number): number =>
    min + Math.floor(random() * (max - min + 1));
  const pick = <Item>(items: readonly Item[]): Item => {
    const item = items[Math.floor(random() * items.length)];
    if (item === undefined) throw new Error('Cannot pick from an empty list.');
    return item;
  };
  const word = (): string => vocabulary[Math.floor(vocabulary.length * random() ** 3)] ?? '';
  const words = (min: number, max: number): string =>
    Array.from({ length: integer(min, max) }, word).join(' ');
  return { random, word, words, integer, pick };
}

function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** A note of a few paragraphs of sentences; returns the document JSON and its plain text. */
function generateNote(generator: Generator): { json: string; plainText: string } {
  const paragraphs = Array.from({ length: generator.integer(1, 5) }, () =>
    Array.from(
      { length: generator.integer(1, 6) },
      () => `${capitalize(generator.words(5, 16))}.`,
    ).join(' '),
  );
  const json = JSON.stringify({
    type: 'doc',
    content: paragraphs.map((text) => ({ type: 'paragraph', content: [{ type: 'text', text }] })),
  });
  return { json, plainText: paragraphs.join('\n') };
}

async function buildDataset(connections: SqliteConnections): Promise<Dataset> {
  const vocabulary = buildVocabulary(createRandom(1));
  const generator = createGenerator(2, vocabulary);
  const nodeIds = Array.from({ length: NODE_COUNT }, (_, index) => uuid(0xa, index + 1) as NodeId);
  const tagIds = Array.from({ length: TAG_COUNT }, (_, index) => uuid(0xc, index + 1) as TagId);
  const titles: string[] = [];

  await connections.runInTransaction(async () => {
    const database = connections.forWrite();

    // Nodes: the FTS triggers index title, summary and plain text as each row is inserted.
    const insertNode = database.prepare(
      `INSERT INTO knowledge_nodes
         (id, workspace_id, title, summary, note_json, note_schema_version, note_plain_text,
          created_at, updated_at)
       VALUES (?, ?, ?, ?, ?, 1, ?, ?, ?)`,
    );
    for (const nodeId of nodeIds) {
      const title = capitalize(generator.words(1, 5));
      const summary = generator.random() < 0.5 ? capitalize(generator.words(5, 20)) : null;
      const note = generateNote(generator);
      titles.push(title);
      insertNode.run(
        nodeId,
        WORKSPACE_ID,
        title,
        summary,
        note.json,
        note.plainText,
        TIMESTAMP,
        TIMESTAMP,
      );
    }

    // Relationships over the seeded built-in types, respecting the schema's rules: no self-links,
    // undirected pairs stored in canonical order (source < target) and no duplicates.
    const types = database
      .prepare('SELECT id, directionality FROM relationship_types WHERE workspace_id = ?')
      .all(WORKSPACE_ID)
      .map((row) => ({ id: String(row.id), directionality: String(row.directionality) }));
    const insertRelationship = database.prepare(
      `INSERT INTO relationships
         (id, workspace_id, source_node_id, target_node_id, type_id, directionality, created_at,
          updated_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
    );
    const seen = new Set<string>();
    while (seen.size < RELATIONSHIP_COUNT) {
      const type = generator.pick(types);
      let source = generator.pick(nodeIds);
      let target = generator.pick(nodeIds);
      if (source === target) continue;
      if (type.directionality === 'undirected' && source > target) {
        [source, target] = [target, source];
      }
      const key = `${source}|${target}|${type.id}`;
      if (seen.has(key)) continue;
      seen.add(key);
      insertRelationship.run(
        uuid(0xb, seen.size),
        WORKSPACE_ID,
        source,
        target,
        type.id,
        type.directionality,
        TIMESTAMP,
        TIMESTAMP,
      );
    }

    // Tags with skewed usage: each node carries zero to four tags.
    const insertTag = database.prepare(
      `INSERT INTO tags (id, workspace_id, display_label, normalized_label, created_at, updated_at)
       VALUES (?, ?, ?, ?, ?, ?)`,
    );
    tagIds.forEach((tagId, index) => {
      const label = `topic ${index} ${vocabulary[index] ?? ''}`;
      insertTag.run(tagId, WORKSPACE_ID, label, label.toLowerCase(), TIMESTAMP, TIMESTAMP);
    });
    const insertNodeTag = database.prepare(
      `INSERT INTO node_tags (workspace_id, node_id, tag_id, created_at) VALUES (?, ?, ?, ?)
       ON CONFLICT (node_id, tag_id) DO NOTHING`,
    );
    for (const nodeId of nodeIds) {
      for (let count = generator.integer(0, 4); count > 0; count -= 1) {
        // Squaring the random value makes low-numbered tags the popular ones.
        const tagId = tagIds[Math.floor(TAG_COUNT * generator.random() ** 2)];
        if (tagId !== undefined) insertNodeTag.run(WORKSPACE_ID, nodeId, tagId, TIMESTAMP);
      }
    }
  });

  return { vocabulary, titles, nodeIds, tagIds };
}

interface Stats {
  readonly count: number;
  readonly p50: number;
  readonly p95: number;
  readonly max: number;
}

/** Nearest-rank percentiles over durations in milliseconds. */
function summarize(durations: readonly number[]): Stats {
  const sorted = [...durations].sort((left, right) => left - right);
  const percentile = (fraction: number): number =>
    sorted[Math.max(0, Math.ceil(fraction * sorted.length) - 1)] ?? Number.NaN;
  return { count: sorted.length, p50: percentile(0.5), p95: percentile(0.95), max: percentile(1) };
}

async function measure(work: () => Promise<unknown>): Promise<number> {
  const start = performance.now();
  await work();
  return performance.now() - start;
}

/** Mixed search workload: plain text plus optional tag filter, cursor and expected-empty flag. */
interface SearchCase {
  readonly kind: string;
  readonly text: string;
  readonly tagIds: readonly TagId[];
  readonly secondPage?: boolean;
}

function buildSearchCases(dataset: Dataset): SearchCase[] {
  const generator = createGenerator(3, dataset.vocabulary);
  const cases: SearchCase[] = [];
  const add = (count: number, create: () => SearchCase): void => {
    for (let index = 0; index < count; index += 1) cases.push(create());
  };
  add(60, () => ({ kind: 'single word', text: generator.word(), tagIds: [] }));
  add(20, () => ({
    kind: 'single word, page 2',
    text: generator.word(),
    tagIds: [],
    secondPage: true,
  }));
  add(50, () => ({
    kind: 'two words',
    text: `${generator.word()} ${generator.word()}`,
    tagIds: [],
  }));
  add(40, () => {
    const word = generator.word();
    return {
      kind: 'prefix',
      text: word.slice(0, Math.min(word.length, generator.integer(2, 4))),
      tagIds: [],
    };
  });
  add(40, () => ({
    kind: 'tag filter',
    text: generator.word(),
    tagIds: Array.from({ length: generator.integer(1, 2) }, () =>
      generator.pick(dataset.tagIds.slice(0, 40)),
    ),
  }));
  add(20, () => ({ kind: 'Hebrew', text: generator.pick(HEBREW_WORDS), tagIds: [] }));
  add(20, () => ({ kind: 'no hits', text: `qzxv${generator.integer(1000, 9999)}`, tagIds: [] }));
  return cases;
}

function buildLookupTexts(dataset: Dataset): string[] {
  const generator = createGenerator(4, dataset.vocabulary);
  return Array.from({ length: 220 }, (_, index) => {
    const title = generator.pick(dataset.titles);
    if (index % 3 === 0) {
      // Substring from the middle of a title (the slow, non-prefix path).
      const start = generator.integer(0, Math.max(0, title.length - 3));
      return title.slice(start, start + 3);
    }
    return title.slice(0, generator.integer(1, 4));
  });
}

// eslint-disable-next-line no-console -- the benchmark's purpose is to print its measurements.
const report = (line: string): void => console.log(line);

function formatRow(label: string, stats: Stats): string {
  const ms = (value: number): string => value.toFixed(2).padStart(9);
  return `${label.padEnd(22)}${String(stats.count).padStart(7)}${ms(stats.p50)}${ms(stats.p95)}${ms(stats.max)}`;
}

describe.skipIf(process.env.MMAP_BENCHMARK !== '1')('search benchmark (PRD §9 dataset)', () => {
  let directory: string;
  let connections: SqliteConnections;
  let dataset: Dataset;

  beforeAll(async () => {
    directory = mkdtempSync(join(tmpdir(), 'mmap-search-benchmark-'));
    connections = (
      await openWorkspaceDatabase(join(directory, 'mmap.sqlite'), { backupDirectory: directory })
    ).connections;
    let counter = 0;
    await createWorkspaceService({
      transactions: connections,
      workspaces: new SqliteWorkspaceRepository(connections),
      relationshipTypes: new SqliteRelationshipTypeRepository(connections),
      ids: { newId: () => uuid(0xd, ++counter) },
      clock: { now: () => TIMESTAMP },
    }).initialize(WORKSPACE_ID, 'Benchmark', 'UTC');

    const start = performance.now();
    dataset = await buildDataset(connections);
    report(`Dataset built in ${((performance.now() - start) / 1000).toFixed(1)} s`);
  }, SETUP_TIMEOUT_MS);

  afterAll(async () => {
    await connections.close();
    rmSync(directory, { recursive: true, force: true });
  });

  it(
    'meets the search and lookup latency targets',
    async () => {
      const database = connections.forRead();
      const count = (table: string): number =>
        Number(database.prepare(`SELECT count(*) AS total FROM ${table}`).get()?.total);
      expect(count('knowledge_nodes')).toBe(NODE_COUNT);
      expect(count('relationships')).toBe(RELATIONSHIP_COUNT);

      const index = new SqliteSearchIndex(connections);
      const searchDurations: number[] = [];
      const durationsByKind = new Map<string, number[]>();
      let totalHits = 0;
      for (const searchCase of buildSearchCases(dataset)) {
        const query = {
          workspaceId: WORKSPACE_ID,
          text: searchCase.text,
          tagIds: searchCase.tagIds,
        };
        let cursor: string | undefined;
        if (searchCase.secondPage === true) {
          cursor = (await index.search({ ...query, page: { limit: 20 } })).nextCursor ?? undefined;
        }
        let hits = 0;
        const duration = await measure(async () => {
          hits = (await index.search({ ...query, page: { limit: 20, cursor } })).totalCount;
        });
        totalHits += hits;
        if (searchCase.kind === 'no hits') expect(hits).toBe(0);
        searchDurations.push(duration);
        durationsByKind.set(searchCase.kind, [
          ...(durationsByKind.get(searchCase.kind) ?? []),
          duration,
        ]);
      }

      const lookupDurations: number[] = [];
      for (const text of buildLookupTexts(dataset)) {
        const exclude = dataset.nodeIds.slice(0, lookupDurations.length % 4);
        lookupDurations.push(
          await measure(() => index.lookupTitles(WORKSPACE_ID, text, 20, exclude)),
        );
      }

      const searchStats = summarize(searchDurations);
      const lookupStats = summarize(lookupDurations);
      report(
        `${'operation'.padEnd(22)}${'count'.padStart(7)}${'p50 ms'.padStart(9)}${'p95 ms'.padStart(9)}${'max ms'.padStart(9)}`,
      );
      report(formatRow('search (all)', searchStats));
      for (const [kind, durations] of durationsByKind) {
        report(formatRow(`  ${kind}`, summarize(durations)));
      }
      report(formatRow('title lookup', lookupStats));
      report(`Average search totalCount: ${(totalHits / searchDurations.length).toFixed(0)}`);

      expect(searchStats.count).toBeGreaterThanOrEqual(200);
      expect(lookupStats.count).toBeGreaterThanOrEqual(200);
      expect(searchStats.p95).toBeLessThan(500);
      expect(lookupStats.p95).toBeLessThan(100);
    },
    SETUP_TIMEOUT_MS,
  );

  it(
    'loads the bounded knowledge graph within budget',
    async () => {
      const graph = new SqliteGraphQuery(connections);
      const typeIds = connections
        .forRead()
        .prepare('SELECT id FROM relationship_types WHERE workspace_id = ? ORDER BY id')
        .all(WORKSPACE_ID)
        .map((row) => String(row.id) as RelationshipTypeId);
      const noFilters = {
        tagIds: [],
        relationshipTypeIds: [],
        mapIds: [],
        text: null,
        includeReferences: true,
      };
      const limits = { maxNodes: MAX_GRAPH_NODES, maxEdges: MAX_GRAPH_EDGES };
      const filterSets = [
        noFilters,
        { ...noFilters, tagIds: dataset.tagIds.slice(0, 1) },
        { ...noFilters, relationshipTypeIds: typeIds.slice(0, 2) },
        { ...noFilters, text: dataset.vocabulary[0] ?? 'a' },
      ];
      const overviewDurations: number[] = [];
      let hub: NodeId | null = null;
      for (let round = 0; round < 5; round += 1) {
        for (const filters of filterSets) {
          overviewDurations.push(
            await measure(async () => {
              const slice = await graph.overview(WORKSPACE_ID, filters, limits);
              hub ??= slice.nodes[0]?.id ?? null;
              if (filters === noFilters) {
                expect(slice.nodes).toHaveLength(MAX_GRAPH_NODES);
                expect(slice.totalNodes).toBe(NODE_COUNT);
              }
            }),
          );
        }
      }
      const neighborhoodDurations: number[] = [];
      for (const nodeId of [hub, ...dataset.nodeIds.slice(0, 49)]) {
        if (nodeId === null) continue;
        neighborhoodDurations.push(
          await measure(() =>
            graph.neighborhood(WORKSPACE_ID, nodeId, noFilters, {
              maxNeighbors: MAX_GRAPH_NEIGHBORS,
              maxEdges: MAX_GRAPH_EDGES,
            }),
          ),
        );
      }
      const overviewStats = summarize(overviewDurations);
      const neighborhoodStats = summarize(neighborhoodDurations);
      report(formatRow('graph overview', overviewStats));
      report(formatRow('graph neighborhood', neighborhoodStats));
      expect(overviewStats.p95).toBeLessThan(1_000);
      expect(neighborhoodStats.p95).toBeLessThan(300);
    },
    SETUP_TIMEOUT_MS,
  );
});
